/** 兜底：万一 config.js 里加了新客人、这里还没写台词 */
const FALLBACK = ['（她冲你笑了笑，把杯子举了起来。）', '生日快乐，哥伦比娅。'];

export function partyTalkOf(id) {
  // config.js 里的 id 带 npc- 前缀（'npc-ainuo'），这里表里的键不带，
  // 统一剥掉前缀再查 —— 否则会静默落到 FALLBACK，
  // 14 个人说同一句话（第一版就是这么错的，验收脚本当场抓到）。
  const key = String(id || '').replace(/^npc-/, '');
  return PARTY_TALK[key] || FALLBACK;
}

